const text = fs.readFileSync(path.join(src, '38_boss_atelier.js'), 'utf8').replace(/\r\n/g, '\n');
const core = fs.readFileSync(path.join(src, '01_core.js'), 'utf8');
const cut = (a, b, what, from = 0) => { const i = text.indexOf(a, from), j = text.indexOf(b, i + a.length); if (i < 0 || j < 0) throw new Error('marker not found: ' + what); return text.slice(i, j).trimEnd(); };

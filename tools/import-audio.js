// node tools/import-audio.js <path to fun-stuff/threshold/src>
// Writes packages/client/src/audio.js: Threshold's sound, copied unchanged and wrapped as one ES module for the Axiom client:
//   03_audio.js         Sound (the synthesised effects: every sfx by name, tones, noise, the reverb, the buses) and Music
//                       (the step sequencer with its intensity layers and voices). No samples, no files.
//   22_boss_duelist.js  Issen's music and its Nightmare version (MUSIC, nmMusic)
//   38_boss_atelier.js  Pentimento's music and its Nightmare version (MUSIC, nmMusic)
// The sim never plays anything: its Sound.* and Music.* calls arrive as cues (sim/src/view.js), and client/src/sound.js
// plays them. The volumes come from client/src/controls.js. Re-run this to pick up sound or music changes in Threshold.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src || !fs.existsSync(path.join(src, '03_audio.js'))) { console.error('usage: node tools/import-audio.js <fun-stuff/threshold/src>'); process.exit(1); }
const read = (f) => fs.readFileSync(path.join(src, f), 'utf8').replace(/\r\n/g, '\n').trimEnd();
const cutIn = (text, a, b, what) => { const i = text.indexOf(a), j = text.indexOf(b, i + a.length); if (i < 0 || j < 0) throw new Error('marker not found: ' + what); return text.slice(i, j + b.length); };
const dedent = (s) => s.replace(/^ {2}/gm, '');

const audio = read('03_audio.js');
// boss music: `const MUSIC = { ... ] };` and `function nmMusic(base) { ... }` (the first line of the file's function ends with "\n  }")
function music(file, id) {
  const t = read(file);
  const M = cutIn(t, '  const MUSIC = {', '] };', id + ' MUSIC'), N = cutIn(t, '  function nmMusic(base) {', '\n  }', id + ' nmMusic');
  return `  ${id}: (() => {\n  ${dedent(M).replace(/\n/g, '\n  ')}\n  ${dedent(N).replace(/\n/g, '\n  ')}\n  return { normal: MUSIC, nightmare: nmMusic(MUSIC) };\n  })(),`;
}

const out = `// GENERATED by tools/import-audio.js from Threshold (fun-stuff threshold/src: 03_audio.js, and the music of
// 22_boss_duelist.js and 38_boss_atelier.js). Do not edit by hand: change the sound in Threshold and re-run the tool.
// client/src/sound.js plays the sim's sound.* and music.* cues through this.
import { Settings } from './controls.js';

// ---------------- prelude: what the Threshold code below reads
const QS = new URLSearchParams(location.search);
const G = { headless: false }; // the client always plays

// ---------------- 03_audio.js ----------------
${audio}

// ---------------- the music of the ported fights (each boss file's MUSIC and nmMusic) ----------------
const BOSS_MUSIC = {
${music('22_boss_duelist.js', 'duelist')}
${music('38_boss_atelier.js', 'atelier')}
};

export { Sound, Music, BOSS_MUSIC };
`;
const dst = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'packages', 'client', 'src', 'audio.js');
fs.writeFileSync(dst, out);
console.log('wrote ' + dst + ' (' + Math.round(out.length / 1024) + ' KB)');

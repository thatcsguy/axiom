// node tools/import-controls.js <path to fun-stuff/threshold/src>
// Writes packages/client/src/controls.js: Threshold's settings and remappable bindings, wrapped as one ES module:
//   01_core.js   the Settings object and saveSettings (Axiom's own defaults and storage key, see the prelude)
//   02_input.js  BIND_ACTIONS, BIND_DEFAULTS, PAD_START, KEY_RESERVED and Binds (lookups, assign with swap, reset, key and
//                pad button names, Xbox / PlayStation glyphs and colours, the hotbar's slot labels), copied unchanged
// Threshold's Input object itself is not copied: Axiom's keyboard, mouse and controller reading is in client/src/game.js,
// and it keeps the few fields Binds reads (device, padKind, padDualSense) on the Input stand-in exported here.
// Re-run this to pick up binding changes in Threshold.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src || !fs.existsSync(path.join(src, '02_input.js'))) { console.error('usage: node tools/import-controls.js <fun-stuff/threshold/src>'); process.exit(1); }
const read = (f) => fs.readFileSync(path.join(src, f), 'utf8').replace(/\r\n/g, '\n').trimEnd();
const input = read('02_input.js'), core = read('01_core.js');
const i = input.indexOf('const BIND_ACTIONS = ['), j = input.indexOf('\nconst Input = {');
if (i < 0 || j < 0) throw new Error('marker not found: Binds block in 02_input.js');
const BINDS = input.slice(i, j).trimEnd();
const m = /const Settings = Object\.assign\((\{[^\n]*\}),/.exec(core); if (!m) throw new Error('Settings defaults not found in 01_core.js');

const out = `// GENERATED by tools/import-controls.js from Threshold (fun-stuff threshold/src: 01_core.js Settings, 02_input.js Binds).
// Do not edit by hand: change the bindings in Threshold and re-run the tool. game.js reads the keyboard, mouse and
// controller through Binds; settings-ui.js is the Settings screen.

// ---------------- prelude: Settings (Threshold's defaults: ${m[1]})
// Axiom keeps the ones that are about this computer and this player's hands: volumes, mouse and camera speed, invert,
// graphics, character height, the controller and its prompts, the bindings. Difficulty, class and the testing toggles are
// chosen in the lobby. Saved in localStorage 'axiom_settings' (an older 'axiom_quality' is picked up once).
const QS = new URLSearchParams(location.search);
const Settings = Object.assign({ vol: 70, mus: 60, sens: 100, psens: 100, inv: false, q: 'high', camY: 50 },
  (() => { try { const q = localStorage.getItem('axiom_quality'); return q ? { q } : {}; } catch (e) { return {}; } })(),
  (() => { try { return JSON.parse(localStorage.getItem('axiom_settings') || '{}'); } catch (e) { return {}; } })());
function saveSettings() { try { localStorage.setItem('axiom_settings', JSON.stringify(Settings)); } catch (e) { /* private mode */ } }
if (QS.get('quality')) Settings.q = QS.get('quality');
// what Binds reads of Threshold's Input: the device the prompts are for and the kind of pad in use (game.js keeps them)
const Input = { device: Settings.pad === true ? 'pad' : 'kbm', padKind: 'xbox', padDualSense: false, padId: '' };
// Binds tells the UI when key names change (the keyboard layout arrives late)
const UI = { deviceChanged() { for (const f of UI.listeners) f(); }, listeners: [] };

// ---------------- 02_input.js: bindings ----------------
${BINDS}

export { Settings, saveSettings, Input, UI, Binds, BIND_ACTIONS, BIND_DEFAULTS, PAD_START, KEY_RESERVED };
`;
const dst = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'packages', 'client', 'src', 'controls.js');
fs.writeFileSync(dst, out);
console.log('wrote ' + dst + ' (' + Math.round(out.length / 1024) + ' KB)');

// node tools/import-heroes.js <path to fun-stuff/threshold/src>
// Writes packages/client/src/heroes.js: Threshold's hero models (the generic buildHero from 07_player.js, the hero kit and
// Stormcaller from 07_hero.js, Duskblade from 07_model_duskblade.js) wrapped as one ES module for the Axiom client.
// The Threshold code is copied unchanged; a short prelude supplies the few globals it reads (math helpers, W.mat / W.glow,
// G.now). Re-run it to pick up model changes in Threshold. Only the MVP's two classes are imported.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src || !fs.existsSync(path.join(src, '07_player.js'))) { console.error('usage: node tools/import-heroes.js <fun-stuff/threshold/src>'); process.exit(1); }
const read = (f) => fs.readFileSync(path.join(src, f), 'utf8');
const player = read('07_player.js'), end = player.indexOf('\nclass Player');
const buildHero = player.slice(player.indexOf('function buildHero'), end).trimEnd();
const out = `// GENERATED by tools/import-heroes.js from Threshold (fun-stuff threshold/src: buildHero in 07_player.js, 07_hero.js,
// 07_model_duskblade.js). Do not edit by hand: change the models in Threshold and re-run the tool.
//
// buildHero(cls) -> { group, update(dt, p), anim, wtip, body, swing(kind, dur) }. update() reads a stand-in p with
// moveSpeed, grounded, casting, parryT, flashT, rollT, aimT, loadT, hasBuff(id), pose. Set HeroClock.now each frame.
import * as THREE from 'three';
const TAU = Math.PI * 2, PI = Math.PI, V3 = THREE.Vector3;
const clamp = (v, a, b) => v < a ? a : v > b ? b : v, lerp = (a, b, t) => a + (b - a) * t, sat = (v) => clamp(v, 0, 1);
const smooth = (t) => { t = sat(t); return t * t * (3 - 2 * t); }, damp = (a, b, k, dt) => lerp(a, b, 1 - Math.exp(-k * dt));
const wrapPi = (a) => { a = (a + PI) % TAU; if (a < 0) a += TAU; return a - PI; }, angDiff = (a, b) => wrapPi(b - a), dampAng = (a, b, k, dt) => a + angDiff(a, b) * (1 - Math.exp(-k * dt));
const vrand = Math.random;
const G = { now: 0, headless: false };
const W = {
  mat(o = {}) { return new THREE.MeshStandardMaterial(Object.assign({ color: 0x888888, roughness: 0.8, metalness: 0 }, o)); },
  glow(color, intensity = 2, o = {}) { return new THREE.MeshBasicMaterial(Object.assign({ color: new THREE.Color(color).multiplyScalar(intensity) }, o)); },
};

// ---------------- 07_player.js: buildHero ----------------
${buildHero}

// ---------------- 07_hero.js ----------------
${read('07_hero.js').trimEnd()}

// ---------------- 07_model_duskblade.js ----------------
${read('07_model_duskblade.js').trimEnd()}

export { buildHero, HERO_MODELS, G as HeroClock };
`;
const dst = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../packages/client/src/heroes.js');
fs.writeFileSync(dst, out);
console.log('wrote ' + dst + ' (' + Math.round(out.length / 1024) + ' KB)');

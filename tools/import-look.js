// node tools/import-look.js <path to fun-stuff/threshold/src>
// Writes packages/client/src/look.js: Threshold's shared look, copied unchanged and wrapped as one ES module for the Axiom
// client, the way tools/import-heroes.js brings over the hero models:
//   01_core.js   the shader math guard, renderer, quality table, post chain (sanitize, bloom, colour grade, flash, pulse)
//   04_fx.js     the FX library (GPU particles, rings, pillars, beams, lightning, slashes, domes, pooled lights, numbers, shake)
//   05_world.js  the camera rig (orbit, zoom, cinematic blend, shake, keep-out-of-the-boss, occluder fade, lens shift) and W
//                (procedural textures, sky, water, lava, motes, lights)
//   06_combat.js the telegraph decal shader and the bullet shaders (strings only: the client draws hazards and bullets
//                from snapshots, see view.js)
//   08_classes.js the HUD icon paths and Stormcaller's pip classes
//   11_warm.js   the warm-up (draw everything once before a fight so no shader compiles mid-fight; constant light counts)
//   12_hitch.js  the freeze log
// A short prelude supplies the globals that code reads (G, Settings, Input, Hooks, a small coroutine runner, ...), and a
// postlude runs one frame the way Threshold's main loop does (Look.frame). Re-run it to pick up look changes in Threshold.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src || !fs.existsSync(path.join(src, '04_fx.js'))) { console.error('usage: node tools/import-look.js <fun-stuff/threshold/src>'); process.exit(1); }
const read = (f) => fs.readFileSync(path.join(src, f), 'utf8').trimEnd();
const between = (text, a, b, what) => { const i = text.indexOf(a), j = text.indexOf(b, i + 1); if (i < 0 || j < 0) throw new Error('marker not found: ' + what); return text.slice(i, j).trimEnd(); };
const grab = (text, re, what) => { const m = re.exec(text); if (!m) throw new Error('not found: ' + what); return m[1]; };

const core = read('01_core.js'), combat = read('06_combat.js'), classes = read('08_classes.js');
const coreLook = between(core, '// ---------- shader math guard ----------', '// ---------- main loop ----------', '01_core.js look');
const HZ_VERT = grab(combat, /const VERT = ('[^\n]*');/, 'hazard VERT'), HZ_FRAG = grab(combat, /const FRAG = (`[\s\S]*?`);/, 'hazard FRAG');
const BUL_V = grab(combat, /const BULV = (`[\s\S]*?`);/, 'BULV'), BUL_F = grab(combat, /const BULF = (`[\s\S]*?`);/, 'BULF');
const ICON = between(classes, 'const ICON = {', '\n};', 'ICON') + '\n};';
const PIPS = between(classes, 'function scPipCls(p, i) {', '\n}\n', 'scPipCls') + '\n}';
const hitch = read('12_hitch.js').replace(/'th_hitch'/g, "'axiom_hitch'").replace('Threshold freeze log', 'Axiom freeze log');

const out = `// GENERATED by tools/import-look.js from Threshold (fun-stuff threshold/src: 01_core.js renderer and post chain, 04_fx.js,
// 05_world.js, the telegraph and bullet shaders of 06_combat.js, 08_classes.js icons, 11_warm.js, 12_hitch.js).
// Do not edit by hand: change the look in Threshold and re-run the tool. Axiom's own drawing (snapshots, cues, arenas,
// hazards, bullets) is in view.js and reads this module.
//
// Look.frame(rdt) runs one frame as Threshold's main loop does: Hooks.frame stage 0, Hooks.step (FX), Hooks.frame stage 1
// (numbers, camera, light keeper), the post chain, the freeze log. Set G.player / G.boss / G.arena (plain stand-ins with the
// fields the camera reads) and Input.lookX / lookY / zoom before each frame.
import * as THREE from 'three';
import { EffectComposer } from 'three/addons/postprocessing/EffectComposer.js';
import { RenderPass } from 'three/addons/postprocessing/RenderPass.js';
import { UnrealBloomPass } from 'three/addons/postprocessing/UnrealBloomPass.js';
import { ShaderPass } from 'three/addons/postprocessing/ShaderPass.js';
import { OutputPass } from 'three/addons/postprocessing/OutputPass.js';

// ---------------- prelude: what the Threshold code below reads
const QS = new URLSearchParams(location.search);
const TAU = Math.PI * 2, PI = Math.PI, V3 = THREE.Vector3;
const $ = (s) => document.querySelector(s);
const clamp = (v, a, b) => v < a ? a : v > b ? b : v, lerp = (a, b, t) => a + (b - a) * t, sat = (v) => clamp(v, 0, 1);
const smooth = (t) => { t = sat(t); return t * t * (3 - 2 * t); }, damp = (a, b, k, dt) => lerp(a, b, 1 - Math.exp(-k * dt));
const wrapPi = (a) => { a = (a + PI) % TAU; if (a < 0) a += TAU; return a - PI; }, angDiff = (a, b) => wrapPi(b - a), dampAng = (a, b, k, dt) => a + angDiff(a, b) * (1 - Math.exp(-k * dt));
const angTo = (x0, z0, x1, z1) => Math.atan2(x1 - x0, z1 - z0);
const vrand = Math.random; // cosmetic only: nothing here reaches the sim
// G: the client's own clocks and the stand-ins the camera reads. headless is always false here (the sim never draws).
const G = { now: 0, ft: 0, rt: 0, dt: 0, rdt: 0, state: 'fight', headless: false, nightmare: false, player: null, boss: null, arena: null, errors: [], warmStats: null, keepDisposed: null };
const Settings = { q: (() => { try { return localStorage.getItem('axiom_quality') || 'high'; } catch (e) { return 'high'; } })(), camY: 50 };
if (QS.get('quality')) Settings.q = QS.get('quality');
const Input = { lookX: 0, lookY: 0, zoom: 0 };
const Hooks = { step: [], frame: [] };
const Game = { def: null };
const Hz = { warm() { } }; // view.js points this at its telegraph pool (Warm.run asks for one decal)
function reportError(e) { const msg = (e && e.stack) ? e.stack.split('\\n').slice(0, 3).join(' | ') : String(e); if (G.errors.length < 30) G.errors.push(msg); console.error(e); }
// a small coroutine runner for the client's own timelines (Post.lerpTo regrades): yield n waits n seconds, bare yield one frame
const Co = {
  list: [],
  start(gen, tag = 'look') { if (typeof gen === 'function') gen = gen(); const c = { gen, tag, wait: 0, dead: false }; this.list.push(c); return c; },
  stopTag(tag) { for (const c of this.list) if (c.tag === tag) { c.dead = true; try { c.gen.return(); } catch (e) { /* ignore */ } } },
  update(dt) {
    for (const c of this.list) {
      if (c.dead) continue; if (c.wait > 0) { c.wait -= dt; if (c.wait > 0) continue; }
      let r; try { r = c.gen.next(); } catch (e) { reportError(e); c.dead = true; continue; }
      if (r.done) c.dead = true; else if (typeof r.value === 'number') c.wait += r.value;
    }
    this.list = this.list.filter((c) => !c.dead);
  },
};

// ---------------- 01_core.js: shader math guard, renderer, post chain, disposeTree ----------------
${coreLook}

// ---------------- 04_fx.js ----------------
${read('04_fx.js')}

// ---------------- 05_world.js ----------------
${read('05_world.js')}

// ---------------- 06_combat.js: telegraph decal and bullet shaders ----------------
const HZ_VERT = ${HZ_VERT};
const HZ_FRAG = ${HZ_FRAG};
const BUL_V = ${BUL_V};
const BUL_F = ${BUL_F};

// ---------------- 08_classes.js: HUD icons, Stormcaller's pips ----------------
${ICON}
${PIPS}

// ---------------- 11_warm.js ----------------
${read('11_warm.js')}

// ---------------- 12_hitch.js ----------------
${hitch}

// ---------------- postlude: one frame, as Threshold's main loop (01_core.js frame()) runs it
Post.init();
let timeScale = 1, slowT = 0;
// a short world slow-down for this viewer only (Duskblade's parry hit-stop): effects and hero animation run at k for dur seconds
function hitstop(k, dur) { timeScale = k; slowT = dur; }
let lastAt = performance.now();
function frame(rdt) {
  const now = performance.now(), gap = now - lastAt; lastAt = now;
  if (rdt <= 0) return 0;
  G.rt += rdt; G.rdt = rdt;
  if (slowT > 0) { slowT -= rdt; if (slowT <= 0) timeScale = 1; }
  const dt = rdt * timeScale;
  try {
    const t0 = performance.now();
    for (const f of Hooks.frame) f(rdt, 0);
    G.dt = dt; G.now += dt; Co.update(dt);
    for (const f of Hooks.step) f(dt);
    for (const f of Hooks.frame) f(rdt, 1);
    const t1 = performance.now();
    Post.update(rdt);
    Post.composer.render();
    if (Hitch.sync) renderer.getContext().finish();
    Hitch.frame(gap, t1 - t0, performance.now() - t1);
  } catch (e) { reportError(e); }
  Input.lookX = Input.lookY = Input.zoom = 0;
  return dt;
}
function setQuality(name) { if (!QUALITY[name]) return; Settings.q = name; try { localStorage.setItem('axiom_quality', name); } catch (e) { /* private mode */ } Post.setQuality(name); }

export { THREE, G, Settings, Input, Hooks, Game, Hz, Co, QS, renderer, scene, camera, QUALITY, Post, FX, Cam, W, Warm, Hitch, SHADER_GUARD, disposeTree,
  HZ_VERT, HZ_FRAG, BUL_V, BUL_F, ICON, scPipCls, frame, hitstop, setQuality };
`;
// Threshold's in-fight HUD styles (00_head.html, the HUD block): boss and target frames, cast bars, player frame, pips,
// hotbar slots, buffs, floating numbers, the hurt vignette, the hint line
const head = read('00_head.html'), hud = between(head, '/* ---------- HUD ---------- */', '#dbg{', '00_head.html HUD css');
const css = `/* GENERATED by tools/import-look.js from Threshold's 00_head.html (the HUD block). Do not edit by hand; Axiom's own
   overrides are in index.html after this file. */
:root{--accent:#e8c77a;--accent2:#fff3cf;--serif:"Palatino Linotype",Palatino,"Book Antiqua",Georgia,serif;--cls:#b98cff}
${hud}
`;
fs.writeFileSync(path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../packages/client/src/hud.css'), css);
const dst = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../packages/client/src/look.js');
fs.writeFileSync(dst, out);
console.log('wrote ' + dst + ' (' + Math.round(out.length / 1024) + ' KB)');
